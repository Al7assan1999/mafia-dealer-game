// [QA] Sprint 13: the architecture rules (docs/architecture.md) as a test, so the structure can't quietly decay again.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

Iterable<File> _dart(String dir) =>
    Directory(dir).listSync(recursive: true).whereType<File>().where((f) => f.path.endsWith('.dart'));

void main() {
  test('no file in lib/ is over 500 lines (the generated l10n excepted)', () {
    final big = [
      for (final f in _dart('lib'))
        if (!f.path.replaceAll('\\', '/').contains('/l10n/') && f.readAsLinesSync().length > 500) '${f.path}: ${f.readAsLinesSync().length}',
    ];
    expect(big, isEmpty);
  });

  test('core/ imports only core/; state/ never imports a screen', () {
    final bad = <String>[];
    for (final f in [..._dart('lib/core'), ..._dart('lib/state')]) {
      final core = f.path.replaceAll('\\', '/').contains('/core/');
      for (final l in f.readAsLinesSync().where((l) => l.startsWith('import ') && l.contains('package:mafia_dealer/'))) {
        if (l.contains('/features/') || (core && l.contains('/state/'))) bad.add('${f.path}: $l');
      }
    }
    expect(bad, isEmpty);
  });

  test('imports inside the app are package imports, never relative', () {
    final bad = [
      for (final f in _dart('lib').where((f) => !f.path.replaceAll(r'\', '/').contains('/l10n/'))) // l10n is generated by Flutter
        for (final l in f.readAsLinesSync())
          if (l.startsWith("import '") && !l.startsWith("import 'package:") && !l.startsWith("import 'dart:")) '${f.path}: $l',
    ];
    expect(bad, isEmpty);
  });
}
